const filled = new Set(['play', 'pause', 'heart', 'star', 'circle', 'step-forward', 'step-backward'])

// Same props as the FontAwesome icon it replaces: name, size, color, style.
const Icon = ({ name, size = 23, color, style }) => {
	const Lucide = icons[name]
	if (!Lucide) return null
	return <Lucide size={size} color={color} fill={filled.has(name) ? color : 'none'} strokeWidth={2} style={style} />
}

export default Icon
